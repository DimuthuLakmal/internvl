from dataclasses import dataclass, field
from typing import Literal, Optional


@dataclass
class ModelArguments:
    """
    Arguments for specifying model, tokenizer, and configurations.
    """
    model_name_or_path: Optional[str] = field(
        default=None,
        metadata={'help': 'Path to a pretrained model (local or from huggingface.co/models).'}
    )
    vision_path: Optional[str] = field(
        default=None,
        metadata={'help': 'Path to a pretrained model (local or from huggingface.co/models).'}
    )
    llm_path: Optional[str] = field(
        default=None,
        metadata={'help': 'Path to a pretrained model (local or from huggingface.co/models).'}
    )
    mlp_path: Optional[str] = field(
        default=None,
        metadata={'help': 'Path to a pretrained model (local or from huggingface.co/models).'}
    )
    freeze_llm: bool = field(
        default=False,
        metadata={'help': 'Set to True to freeze the LLM. Default is False.'},
    )
    freeze_backbone: bool = field(
        default=False,
        metadata={'help': 'Set to True to freeze the ViT. Default is False.'},
    )
    freeze_mlp: bool = field(
        default=False,
        metadata={'help': 'Set to True to freeze the MLP. Default is False.'},
    )
    unfreeze_vit_layers: int = field(
        default=0,
        metadata={'help': 'Specify the number of ViT layers to unfreeze. Default is 0.'},
    )
    vision_select_layer: int = field(
        default=-1,
        metadata={'help': 'Specify the layer of ViT feature map to use. Default is -1 for the last layer.'},
    )
    use_backbone_lora: int = field(
        default=0,
        metadata={'help': 'Set the LoRA adapter rank for the ViT. Default is 0.'}
    )
    use_llm_lora: int = field(
        default=0,
        metadata={'help': 'Set the LoRA adapter rank for the LLM. Default is 0.'}
    )
    unfreeze_lm_head: bool = field(
        default=False,
        metadata={'help': 'Set to True to unfreeze the head of LLM. Default is False.'},
    )
    grad_checkpoint: bool = field(
        default=True,
        metadata={'help': 'Set to True to use gradient checkpointing. Default is True.'},
    )
    drop_path_rate: float = field(
        default=0.0,
        metadata={'help': 'Set the drop path rate for the ViT. Default is 0.'},
    )
    vision_lr: Optional[float] = field(
        default=None,
        metadata={'help': 'Learning rate for the ViT (vision_model). Default is None, which uses --learning_rate. '
                          'Requires a DeepSpeed config without an "optimizer" section.'},
    )
    vit_layer_decay: float = field(
        default=1.0,
        metadata={'help': 'Layer-wise LR decay for the ViT: layer i of N gets vision_lr * decay ** (N - i). '
                          'Default is 1.0 (no decay).'},
    )
    ema_decay: float = field(
        default=0.999,
        metadata={'help': 'Decay of the EMA copy of trainable weights, updated once per optimizer step and saved as '
                          'ema_trainable.pt in each checkpoint. Set to 0 to disable. Default is 0.999.'},
    )
    ps_version: Literal['v1', 'v2'] = field(
        default='v2',
        metadata={'help': 'Specify the version of pixel shuffle implementation. Default is v2.'}
    )
    use_fast_tokenizer: bool = field(
        default=False,
        metadata={'help': 'Set to True to use the fast mode of the tokenizer.'}
    )
    use_liger: bool = field(
        default=False,
        metadata={'help': 'Set to True to use the liger kernel.'}
    )
    load_lora_adapters: int = field(
        default=0,
        metadata={'help': 'User Lora Apaters saved with Checpoints'}
    )
    load_checkpoint: bool = field(
        default=False,
        metadata={'help': 'Whether to resume the LLM and the MLLM Goal Predictor from a component checkpoint '
                          '(as saved by TargetSFTTrainer), instead of initializing them from scratch.'},
    )
